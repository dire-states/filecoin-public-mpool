// Short actor labels for the UI and the CSVs.
export const ACTOR_LABELS: Record<string, string> = {
  storageminer: 'miner',
  storagemarket: 'market',
  storagepower: 'power',
  verifiedregistry: 'verifreg',
  paymentchannel: 'paych',
}

export function actorLabel(actor: string): string {
  return ACTOR_LABELS[actor] ?? actor
}

// The FVM accepts the EVM InvokeContract method on Ethereum accounts and placeholders (addresses
// not yet deployed) as a plain value transfer, which is how Ethereum wallets send FIL there.
const EVM_INVOKE_CONTRACT = 3844450837
const ETH_RECEIVERS = new Set(['ethaccount', 'placeholder'])

// Method 0 is a plain value transfer on every actor.
export function methodName(actor: string, method: number): string {
  if (method === 0) return 'Send'
  if (method === EVM_INVOKE_CONTRACT && ETH_RECEIVERS.has(actor)) return 'InvokeContract'
  return METHODS[actor]?.[method] ?? `#${method}`
}
